#!/usr/bin/env node
// Writes THIRD-PARTY-LICENSES.md: every package that ends up in a production install (npm ci --omit=dev), with its
// version and licence, read from node_modules. Run `npm run licenses` after changing dependencies.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const rows = [];
for (const [key, info] of Object.entries(lock.packages)) {
  if (!key || info.dev || info.devOptional) continue;
  const name = key.replace(/^.*node_modules\//, '');
  let license = info.license;
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, key, 'package.json'), 'utf8'));
    license = license || (typeof pkg.license === 'string' ? pkg.license : pkg.license && pkg.license.type) || 'UNKNOWN';
  } catch {
    license = license || 'UNKNOWN';
  }
  rows.push([name, info.version, license]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
const unknown = rows.filter((r) => r[2] === 'UNKNOWN');
const out = [
  '# Third-party licences',
  '',
  'OpenParlor itself is MIT licensed (see LICENSE). A production install includes these packages:',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} |`),
  '',
  'Generated by `npm run licenses` from package-lock.json. Each package carries its own licence text in node_modules.',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'THIRD-PARTY-LICENSES.md'), out);
console.log(`${rows.length} packages written to THIRD-PARTY-LICENSES.md`);
if (unknown.length) {
  console.error(`No licence found for: ${unknown.map((r) => r[0]).join(', ')}`);
  process.exit(1);
}
